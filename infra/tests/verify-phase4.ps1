    }
    Write-Host "Verified old ReplicaSet remained intact and serving traffic!"
}

# Check 5: Idempotent apply: re-deploy existing release twice -> no duplicate objects, pod names/restart counts unchanged
Assert-Check "5. Idempotent apply: re-deploy release twice -> identical state, no duplicates, pods/restarts unchanged" {
    $targetReleaseId = $script:nodeReleaseId2
    if (-not $targetReleaseId) { $targetReleaseId = $script:nodeReleaseId1 }
    Write-Host "Re-deploying release $targetReleaseId via POST /api/releases/$targetReleaseId/deploy..."

    $deploy1 = Invoke-RestMethod -Uri "http://localhost:3000/api/releases/$targetReleaseId/deploy" -Method Post
    Write-Host "First deploy result: $($deploy1 | ConvertTo-Json -Compress)"

    # Wait for deployment to settle and any old pods from previous tests to clear
    Start-Sleep -Seconds 5

    # Capture pod names and restart counts before second deploy
    $podsBefore = kubectl get pods -n apps-node-app -l app=node-app -o json | ConvertFrom-Json
    $podNamesBefore = @($podsBefore.items | ForEach-Object { $_.metadata.name }) | Sort-Object
    $podRestartsBefore = @{}
    foreach ($p in $podsBefore.items) {
        $name = $p.metadata.name
        $sumRestarts = ($p.status.containerStatuses | Measure-Object -Property restartCount -Sum).Sum
        $podRestartsBefore[$name] = $sumRestarts
    }
    Write-Host "Pods before second deploy: $($podNamesBefore -join ', ')"

    # Trigger second deploy of identical release
    $deploy2 = Invoke-RestMethod -Uri "http://localhost:3000/api/releases/$targetReleaseId/deploy" -Method Post
    Write-Host "Second deploy result: $($deploy2 | ConvertTo-Json -Compress)"

    # Wait a few seconds to verify pods are untouched
    Start-Sleep -Seconds 5

    $podsAfter = kubectl get pods -n apps-node-app -l app=node-app -o json | ConvertFrom-Json
    $podNamesAfter = @($podsAfter.items | ForEach-Object { $_.metadata.name }) | Sort-Object
    $podRestartsAfter = @{}
    foreach ($p in $podsAfter.items) {
        $name = $p.metadata.name
        $sumRestarts = ($p.status.containerStatuses | Measure-Object -Property restartCount -Sum).Sum
        $podRestartsAfter[$name] = $sumRestarts
    }
    Write-Host "Pods after second deploy: $($podNamesAfter -join ', ')"

    # Verify pod names match exactly
    if ($podNamesBefore.Count -eq 0 -or $podNamesAfter.Count -eq 0) {
        throw "No pods found in namespace apps-node-app"
    }
    $namesDiff = Compare-Object $podNamesBefore $podNamesAfter
    if ($namesDiff) {
        throw "Pod names changed after idempotent deploy! Before: $($podNamesBefore -join ', ') After: $($podNamesAfter -join ', ')"
    }

    # Verify restart counts unchanged
    foreach ($name in $podNamesBefore) {
        if ($podRestartsBefore[$name] -ne $podRestartsAfter[$name]) {
            throw "Pod $name restart count changed! Before: $($podRestartsBefore[$name]), After: $($podRestartsAfter[$name])"
        }
    }
    Write-Host "Pod names and restart counts strictly unchanged!"

    # Check objects count
    $svcCount = (kubectl get svc -n apps-node-app -l app=node-app --no-headers | Measure-Object).Count
    $ingCount = (kubectl get ingress -n apps-node-app -l app=node-app --no-headers | Measure-Object).Count
    $depCount = (kubectl get deployment -n apps-node-app -l app=node-app --no-headers | Measure-Object).Count

    Write-Host "Object counts: Deployments=$depCount, Services=$svcCount, Ingresses=$ingCount"
    if ($depCount -ne 1 -or $svcCount -ne 1 -or $ingCount -ne 1) {
        throw "Duplicate objects detected! Dep=$depCount, Svc=$svcCount, Ing=$ingCount"
    }

    # Verify app is still 100% healthy
    $resp = curl.exe -k -s -w "`nHTTP_STATUS:%{http_code}" --resolve "node-app.pushr.localhost:443:127.0.0.1" https://node-app.pushr.localhost/health
    if (($resp -join "`n") -notmatch "HTTP_STATUS:200") {
        throw "App is not healthy after idempotent re-deploy"
    }
    Write-Host "Idempotency confirmed: objects cleanly updated, pod identities and restart counts preserved, app fully healthy."
}

# Check 6: Per-app namespace isolation: apps-<slug> contains its own Deployment/Service/Ingress
Assert-Check "6. Per-app namespace isolation: apps-<slug> contains its own Deployment/Service/Ingress" {
    $apps = @("node-app", "python-app")
    foreach ($app in $apps) {
        $ns = "apps-$app"
        Write-Host "Checking resources in namespace $ns..."

        # Verify namespace exists
        $nsObj = kubectl get namespace $ns -o jsonpath='{.metadata.name}' 2>&1
        if ($nsObj -ne $ns) {
            throw "Namespace $ns does not exist!"
        }

        # Verify deployment exists in namespace
        $dep = kubectl get deployment $app -n $ns -o jsonpath='{.metadata.name}' 2>&1
        if ($dep -ne $app) {
            throw "Deployment $app does not exist in namespace $ns!"
        }

        # Verify service exists in namespace
        $svc = kubectl get service $app -n $ns -o jsonpath='{.metadata.name}' 2>&1
        if ($svc -ne $app) {
            throw "Service $app does not exist in namespace $ns!"
        }

        # Verify ingress exists in namespace
        $ing = kubectl get ingress $app -n $ns -o jsonpath='{.metadata.name}' 2>&1
        if ($ing -ne $app) {
            throw "Ingress $app does not exist in namespace $ns!"
        }

        # Verify no leaking into default namespace
        $depDefault = kubectl get deployment $app -n default --ignore-not-found=true -o jsonpath='{.metadata.name}'
        if ($depDefault -eq $app) {
            throw "Deployment $app leaked into default namespace!"
        }
        $svcDefault = kubectl get service $app -n default --ignore-not-found=true -o jsonpath='{.metadata.name}'
        if ($svcDefault -eq $app) {
            throw "Service $app leaked into default namespace!"
        }

        Write-Host "Namespace $ns verified with dedicated Deployment, Service, and Ingress."
    }
}

