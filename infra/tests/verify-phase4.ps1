Write-Host "==========================================" -ForegroundColor Magenta

# Check 1: Push node-app -> Buildpack -> auto deploy -> https://node-app.pushr.localhost returns 200 with valid TLS
Assert-Check "1. Push node-app: auto-deploy -> https://node-app.pushr.localhost returns 200 with TLS" {
    Write-Host "Triggering build for node-app (Phase 4)..."
    $body = @{
        appSlug = "node-app"
        commitSha = "c1d2e3f4a5b600112233445566778899aabb0101"
        ref = "refs/heads/main"
    } | ConvertTo-Json

    $res = Invoke-RestMethod -Uri "http://localhost:3000/api/internal/releases/build" -Method Post -Body $body -ContentType "application/json"
    $releaseId = $res.releaseId
    $script:nodeReleaseId1 = $releaseId
    Write-Host "Release created with ID: $releaseId"

    # Poll status until build and deploy succeed
    $buildStatus = "queued"
    $deployStatus = "pending"
    for ($i = 0; $i -lt 80; $i++) {
        Start-Sleep -Seconds 3
        $rel = Invoke-RestMethod -Uri "http://localhost:3000/api/releases/$releaseId"
        $buildStatus = $rel.status
        $deployStatus = $rel.deployStatus
        Write-Host "Release build: $buildStatus, deploy: $deployStatus"
        if ($buildStatus -eq "failed" -or $deployStatus -eq "failed") { break }
        if ($buildStatus -eq "succeeded" -and $deployStatus -eq "deployed") { break }
    }

    if ($buildStatus -ne "succeeded" -or $deployStatus -ne "deployed") {
        $errDetail = if ($rel.deployError) { $rel.deployError } else { $rel.error }
        throw "Deployment did not succeed. Build: $buildStatus, Deploy: $deployStatus, Error: $errDetail"
    }

    # Verify namespace exists
    $ns = kubectl get namespace apps-node-app -o jsonpath='{.metadata.name}' 2>&1
    if ($ns -ne "apps-node-app") { throw "Namespace apps-node-app was not created" }

    # Wait for TLS secret node-app-tls
    Write-Host "Waiting for cert-manager to generate node-app-tls secret..."
    $certReady = $false
    for ($i = 0; $i -lt 30; $i++) {
        $secret = kubectl -n apps-node-app get secret node-app-tls --ignore-not-found=true -o jsonpath='{.metadata.name}'
        if ($secret -eq "node-app-tls") {
            $certReady = $true
            break
        }
        Start-Sleep -Seconds 2
    }
    if (-not $certReady) { throw "TLS secret node-app-tls was not generated by cert-manager" }

    # Test HTTPS request
    Write-Host "Testing HTTPS request to https://node-app.pushr.localhost/health..."
    $response = curl.exe -k -s -w "`nHTTP_STATUS:%{http_code}" --resolve "node-app.pushr.localhost:443:127.0.0.1" https://node-app.pushr.localhost/health
    $responseStr = $response -join "`n"
    Write-Host "Response: $responseStr"
    if ($responseStr -notmatch "HTTP_STATUS:200" -or $responseStr -notmatch '"status":\s*"ok"') {
        throw "HTTPS request failed or did not return status ok. Output: $responseStr"
    }
}

# Check 2: Zero downtime rolling update: Push new commit for node-app while hammering ingress
Assert-Check "2. Push new commit: concurrent curl loop during rollout confirms zero downtime (100% 200s)" {
    Write-Host "Triggering second release for node-app..."
    $body = @{
        appSlug = "node-app"
        commitSha = "c1d2e3f4a5b600112233445566778899aabb0102"
        ref = "refs/heads/main"
    } | ConvertTo-Json

    $res = Invoke-RestMethod -Uri "http://localhost:3000/api/internal/releases/build" -Method Post -Body $body -ContentType "application/json"
    $releaseId = $res.releaseId
    $script:nodeReleaseId2 = $releaseId
    Write-Host "Second release created with ID: $releaseId"

    $codes = [System.Collections.Generic.List[int]]::new()
    $done = $false
    $startTime = Get-Date

    Write-Host "Hammering ingress with concurrent requests during rolling update..."
    while (-not $done -and ((Get-Date) - $startTime).TotalSeconds -lt 150) {
        # Fire 5 rapid requests per iteration
        for ($k = 0; $k -lt 5; $k++) {
            $codeStr = curl.exe -k -s -o /dev/null -w "%{http_code}" --resolve "node-app.pushr.localhost:443:127.0.0.1" https://node-app.pushr.localhost/health
            $cleanCode = ($codeStr -replace '\D','').Trim()
            $intCode = 0
            if ([int]::TryParse($cleanCode, [ref]$intCode)) {
                $codes.Add($intCode)
            } else {
                $codes.Add(0)
            }
        }

        # Check release status
        $rel = Invoke-RestMethod -Uri "http://localhost:3000/api/releases/$releaseId"
        if ($rel.deployStatus -eq "deployed" -or $rel.deployStatus -eq "failed") {
            $done = $true
        }
        Start-Sleep -Milliseconds 800
    }

    Write-Host "Total requests sent during rollout window: $($codes.Count)"
    $non200s = $codes | Where-Object { $_ -ne 200 }
    if ($non200s.Count -gt 0) {
        throw "Detected non-200 HTTP responses during rollout: $($non200s -join ', ')"
    }
    if ($codes.Count -lt 20) {
        throw "Expected at least 20 requests during rollout window, only got $($codes.Count)"
    }

    $finalRel = Invoke-RestMethod -Uri "http://localhost:3000/api/releases/$releaseId"
    if ($finalRel.deployStatus -ne "deployed") {
        throw "Second rollout did not succeed. Final deployStatus: $($finalRel.deployStatus)"
    }
    Write-Host "Zero-downtime verified! 100% of $($codes.Count) requests returned HTTP 200."
}

# Check 3: Deploy python-app and confirm both apps are reachable simultaneously at distinct subdomains
Assert-Check "3. Deploy python-app: both apps reachable simultaneously at distinct subdomains" {
    Write-Host "Triggering build for python-app (Phase 4)..."
    $body = @{
        appSlug = "python-app"
        commitSha = "c1d2e3f4a5b600112233445566778899aabb0103"
        ref = "refs/heads/main"
    } | ConvertTo-Json

    $res = Invoke-RestMethod -Uri "http://localhost:3000/api/internal/releases/build" -Method Post -Body $body -ContentType "application/json"
    $releaseId = $res.releaseId
    $script:pythonReleaseId = $releaseId
    Write-Host "Release created with ID: $releaseId"

    for ($i = 0; $i -lt 80; $i++) {
        Start-Sleep -Seconds 3
        $rel = Invoke-RestMethod -Uri "http://localhost:3000/api/releases/$releaseId"
        if ($rel.status -eq "failed" -or $rel.deployStatus -eq "failed") { break }
        if ($rel.status -eq "succeeded" -and $rel.deployStatus -eq "deployed") { break }
    }

    if ($rel.deployStatus -ne "deployed") {
        throw "python-app deployment did not succeed. Build: $($rel.status), Deploy: $($rel.deployStatus)"
    }

    # Wait for python-app TLS secret
    Write-Host "Waiting for cert-manager to generate python-app-tls secret..."
    for ($i = 0; $i -lt 30; $i++) {
        $secret = kubectl -n apps-python-app get secret python-app-tls --ignore-not-found=true -o jsonpath='{.metadata.name}'
        if ($secret -eq "python-app-tls") { break }
        Start-Sleep -Seconds 2
    }

    # Verify node-app hits node-app
    $resNode = curl.exe -k -s --resolve "node-app.pushr.localhost:443:127.0.0.1" https://node-app.pushr.localhost/health
    Write-Host "node-app response: $resNode"
    if ($resNode -notmatch '"app":\s*"node-app"') {
        throw "node-app response did not contain expected app identifier: $resNode"
    }

    # Verify python-app hits python-app
    $resPy = curl.exe -k -s --resolve "python-app.pushr.localhost:443:127.0.0.1" https://python-app.pushr.localhost/health
    Write-Host "python-app response: $resPy"
    if ($resPy -notmatch '"app":\s*"python-app"') {
        throw "python-app response did not contain expected app identifier: $resPy"
    }
}

